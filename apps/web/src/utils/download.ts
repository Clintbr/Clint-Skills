import JSZip from 'jszip';
import type { Skill } from '@claude-skills/core';

/**
 * Downloads a single text/markdown file to the user's browser.
 */
export function downloadFile(filename: string, content: string, mimeType = 'text/markdown;charset=utf-8') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Assembles and downloads a complete ZIP package of the skill,
 * including SKILL.md, references, and examples with clean folder structure.
 */
export async function downloadSkillZip(skill: Skill) {
  const zip = new JSZip();

  // Root folder inside the zip: <slug>/
  const folder = zip.folder(skill.slug);
  if (!folder) {
    throw new Error('Failed to create ZIP directory');
  }

  // 1. Add canonical SKILL.md
  folder.file('SKILL.md', skill.content ? `---\nname: ${skill.name}\nslug: ${skill.slug}\ncategory: ${skill.category}\ndifficulty: ${skill.difficulty}\nversion: ${skill.version}\nlastUpdated: ${skill.lastUpdated}\n---\n\n${skill.content}` : skill.files[0]?.content || '');

  // 2. Add all references
  if (skill.references && skill.references.length > 0) {
    const refFolder = folder.folder('references');
    for (const ref of skill.references) {
      refFolder?.file(ref.name, ref.content);
    }
  }

  // 3. Add all examples
  if (skill.examples && skill.examples.length > 0) {
    const exFolder = folder.folder('examples');
    for (const ex of skill.examples) {
      exFolder?.file(ex.name, ex.content);
    }
  }

  // 4. Add installation helper README
  folder.file(
    'INSTALL.md',
    `# Installation Instructions for ${skill.name}

## Project-Level Installation
Copy this entire folder into your project's \`.claude/skills/\` directory:

\`\`\`
your-project/
  └── .claude/
        └── skills/
              └── ${skill.slug}/
                    ├── SKILL.md
                    ├── references/
                    └── examples/
\`\`\`

## Personal Global Installation
Copy this entire folder to your personal Claude Code skills directory:
- Linux / macOS: \`~/.claude/skills/${skill.slug}/\`
- Windows: \`%USERPROFILE%\\.claude\\skills\\${skill.slug}\\\`

Generated by Clint-Skills — Claude Code Skills Library.
`
  );

  const content = await zip.generateAsync({ type: 'blob' });
  const url = URL.createObjectURL(content);
  const link = document.createElement('a');
  link.href = url;
  link.download = `${skill.slug}-skill-bundle.zip`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Safely copies text to the clipboard and returns whether it succeeded.
 */
export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return true;
    }
    // Fallback for non-secure contexts
    const textArea = document.createElement('textarea');
    textArea.value = text;
    textArea.style.position = 'fixed';
    textArea.style.left = '-999999px';
    document.body.appendChild(textArea);
    textArea.focus();
    textArea.select();
    const successful = document.execCommand('copy');
    document.body.removeChild(textArea);
    return successful;
  } catch (err) {
    console.error('Clipboard copy failed:', err);
    return false;
  }
}

